#!/usr/bin/env python3
"""Write one human-readable report per model into reports/.

Each report is the latest run for that model: the prompt, the completion
verbatim, and every judge verdict with the quote the judge used. The leaderboard
table says "100%"; this is where you read what the model actually wrote.

Reports are generated from leaderboard.json plus the run file each entry points
at, so they cannot drift from the numbers. A report for a model that is no
longer on the board is deleted, which keeps the directory a faithful view of the
current board; git history keeps the older text.

Latest run overrides the previous one, at a stable path, so links never rot.

Usage:
    python3 scripts/reports.py            # rewrite reports/
    python3 scripts/reports.py --check    # exit 1 if reports/ is out of date
"""

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from leaderboard import (  # noqa: E402
    ROOT,
    REPORTS_DIR,
    DataError,
    badge_text,
    cell,
    compute_badges,
    fence,
    fmt_money,
    latest_per_model,
    load_entries,
    ranked,
    slugify,
    total_tests,
    truncate,
)

HEADER = (
    "_Generated by `scripts/reports.py` from the latest run for this model. "
    "Do not edit by hand._"
)


def load_run(entry: dict) -> dict:
    source = entry.get("source_run")
    if not source:
        raise DataError(f"{entry['model']}: no source_run, cannot build a report")
    path = ROOT / source
    if not path.is_file():
        raise DataError(f"{entry['model']}: source_run {source} does not exist")
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise DataError(f"{entry['model']}: {source} is not valid JSON: {exc}") from exc


def completions_by_test(run: dict) -> dict[str, dict]:
    return {o.get("test_id"): o for o in run.get("outputs", []) if o.get("test_id")}


def summary(entry: dict) -> str:
    judge = entry.get("judge", {})
    tokens = (
        f"{entry.get('prompt_tokens', 0)} in / {entry.get('completion_tokens', 0)} out"
    )
    if entry.get("reasoning_tokens"):
        tokens += f" ({entry['reasoning_tokens']} reasoning)"
    evidence = []
    if entry.get("source_run"):
        evidence.append(f"[run](../{entry['source_run']})")
    if entry.get("source_scores"):
        evidence.append(f"[verdicts](../{entry['source_scores']})")

    rows = [
        ("Provider", f"`{cell(entry['provider'])}`"),
        ("Run", f"`{cell(entry.get('run_id', 'n/a'))}`"),
        ("Run at", f"`{cell(entry.get('timestamp', 'n/a'))}`"),
        ("Judge", f"`{cell(judge.get('model', 'n/a'))}` (`{cell(judge.get('protocol', 'n/a'))}`)"),
        ("Strict pass", f"{entry['strict_pass_count']}/{total_tests(entry)}"),
        ("Nuance", f"{entry['nuance_score']:.1f}%"),
        ("Latency", f"{entry['elapsed_seconds']:.1f}s"),
        ("Cost", fmt_money(entry)),
        ("Tokens", tokens),
        ("Badges", badge_text(entry)),
        ("Evidence", ", ".join(evidence) or "n/a"),
    ]
    lines = ["| | |", "|:--|:--|"]
    lines += [f"| {label} | {value} |" for label, value in rows]
    return "\n".join(lines)


def scores_table(entry: dict) -> str:
    lines = ["| Test | Result | Checks |", "|:--|:--|:--:|"]
    for tid, score in sorted(entry["test_scores"].items()):
        result = "pass" if score.get("strict_pass") else "fail"
        lines.append(
            f"| `{cell(tid)}` | {result} | "
            f"{score.get('passed_checks', '?')}/{score.get('total_checks', '?')} |"
        )
    return "\n".join(lines)


def checks_table(score: dict) -> str:
    lines = [
        "| Check | Verdict | Judge reason | Judge evidence |",
        "|:--|:--|:--|:--|",
    ]
    for check in score.get("checks", []):
        verdict = "pass" if check.get("pass") else "fail"
        reason = cell(check.get("reason", ""))
        evidence = cell(truncate(check.get("evidence", ""), 140))
        if check.get("audit"):
            reason = f"{reason} **({cell(check['audit'])})**"
        lines.append(f"| {cell(check.get('item', ''))} | {verdict} | {reason} | {evidence} |")
    return "\n".join(lines)


def render_report(entry: dict) -> str:
    run = load_run(entry)
    completions = completions_by_test(run)

    parts = [
        f"# {entry['model']}",
        "",
        HEADER,
        "",
        summary(entry),
        "",
        "## Result by test",
        "",
        scores_table(entry),
    ]

    for tid, score in sorted(entry["test_scores"].items()):
        output = completions.get(tid) or {}
        result = "pass" if score.get("strict_pass") else "fail"
        parts += [
            "",
            f"## `{tid}` ({result})",
            "",
            "Prompt:",
            "",
            fence(output.get("prompt", "(prompt not recorded in the run file)")),
            "",
            "Completion:",
            "",
            fence(
                output.get("completion")
                or "(empty completion: the model produced no answer text)"
            ),
            "",
            "Checks:",
            "",
            checks_table(score),
        ]

    return "\n".join(parts) + "\n"


def build() -> dict[Path, str]:
    """Return {report path: content} for the current board."""
    entries = ranked(latest_per_model(load_entries()))
    compute_badges(entries)
    return {
        REPORTS_DIR / f"{slugify(entry['model'])}.md": render_report(entry)
        for entry in entries
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if reports/ is stale")
    args = parser.parse_args()

    try:
        expected = build()
    except DataError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1

    existing = {p for p in REPORTS_DIR.glob("*.md")} if REPORTS_DIR.is_dir() else set()
    stale = sorted(existing - set(expected))
    missing = sorted(p for p, text in expected.items() if not p.is_file())
    changed = sorted(
        p for p, text in expected.items() if p.is_file() and p.read_text(encoding="utf-8") != text
    )

    if args.check:
        problems = []
        if missing:
            problems.append(f"missing: {', '.join(p.name for p in missing)}")
        if changed:
            problems.append(f"out of date: {', '.join(p.name for p in changed)}")
        if stale:
            problems.append(f"stale, not on the board: {', '.join(p.name for p in stale)}")
        if problems:
            print(
                "error: reports/ is out of date ("
                + "; ".join(problems)
                + "). Run: python3 scripts/reports.py",
                file=sys.stderr,
            )
            return 1
        print(f"reports/ is up to date ({len(expected)} report(s)).")
        return 0

    REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    written = 0
    for path, text in sorted(expected.items()):
        if path.is_file() and path.read_text(encoding="utf-8") == text:
            continue
        path.write_text(text, encoding="utf-8")
        written += 1
    for path in stale:
        path.unlink()

    summary_bits = [f"{written} written"]
    if stale:
        summary_bits.append(f"{len(stale)} removed")
    print(
        f"reports/: {', '.join(summary_bits)}, {len(expected)} report(s) on the board."
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
